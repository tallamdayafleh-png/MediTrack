import Foundation

/// Where an event came from. Keeping this explicit means test events can never be
/// mistaken for real sensor data in screenshots or experimental results.
enum EventSource: String, Codable {
    case hardware        // received over BLE from the MG24
    case developerTest   // generated by the Debug screen
}

struct MedicationEvent: Identifiable, Codable, Equatable {
    let id: UUID
    let type: MedicationEventType
    /// When the iPhone received the event (the firmware does not send its own timestamp yet).
    let timestamp: Date
    /// Raw load-cell count difference. These are NOT grams.
    let weightDifference: Int?
    /// Whether the IMU detected movement, if the firmware sent that field.
    let movementDetected: Bool?
    let source: EventSource
    /// The exact text received over BLE, kept for debugging.
    let rawPayload: String?

    init(id: UUID = UUID(),
         type: MedicationEventType,
         timestamp: Date = Date(),
         weightDifference: Int? = nil,
         movementDetected: Bool? = nil,
         source: EventSource,
         rawPayload: String? = nil) {
        self.id = id
        self.type = type
        self.timestamp = timestamp
        self.weightDifference = weightDifference
        self.movementDetected = movementDetected
        self.source = source
        self.rawPayload = rawPayload
    }

    var isTest: Bool { source == .developerTest }
}
